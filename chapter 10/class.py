class Employee:
    language = "Java"
    salary = 125000 

arbaz = Employee()
arbaz.name = "Arbaz"
print(arbaz.name, arbaz.salary, arbaz.language)

akib = Employee()
akib.name = "Akib"
print(akib.name, akib.salary, akib.language)

#Here name is instance attribute and salary and language attributes as they directly belong to the class